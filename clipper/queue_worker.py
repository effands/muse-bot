def _is_transient_error(exc):
    """True kalau error ini layak dicoba ulang (sementara: jaringan/timeout/
    server 5xx). Error permanen (kuota habis, token invalid, tidak ditemukan)
    TIDAK di-retry."""
    try:
        status = getattr(getattr(exc, "resp", None), "status", None)
        if status is not None:
            if status >= 500 or status in (408, 429):
                return True
            if status < 500:
                return False
    except Exception:
        pass
    text = str(exc).lower()
    if any(m in text for m in ("quotaexceeded", "uploadlimitexceeded",
                               "invalid_grant", "revoked", "expired",
                               "forbidden", "not found", "bad request")):
        return False
    return any(m in text for m in ("timed out", "timeout", "connection",
                                   "network", "temporarily", "temporary",
                                   "503", "502", "504", "429", "500",
                                   "reset", "broken pipe", "eof",
                                   "rate limit", "backend error",
                                   "server error"))


def extract_transcript_text(srt_path, max_chars=500):
    """Ambil teks polos dari file SRT (tanpa nomor & timestamp) untuk dipakai
    sebagai bahan judul/deskripsi klip."""
    if not srt_path or not os.path.exists(srt_path):
        return ""
    try:
        with open(srt_path, "r", encoding="utf-8", errors="ignore") as f:
            lines = f.read().splitlines()
        words = []
        for line in lines:
            s = line.strip()
            if not s or s.isdigit() or "-->" in s:
                continue
            words.append(s)
        text = " ".join(" ".join(words).split())
        return text[:max_chars]
    except Exception:
        return ""


def build_clip_title(transcript, batch_index):
    """Judul klip dari kata-kata pertama transkrip (bukan lagi selalu
    'Viral Moment #N'). Tanpa transkrip → fallback lama."""
    words = (transcript or "").split()
    if not words:
        return f"Viral Moment #{batch_index} #shorts"
    head = " ".join(words[:8])
    if len(head) > 90:
        head = head[:90].rsplit(" ", 1)[0]
    return f"{head} #shorts"


def build_clip_description(transcript):
    """Deskripsi klip dari kutipan transkrip (maks ~400 karakter) + #shorts.
    Tanpa transkrip → deskripsi generik lama."""
    excerpt = " ".join((transcript or "").split())
    if not excerpt:
        return "Auto-generated by Pabrik Konten Clipper"
    if len(excerpt) > 400:
        excerpt = excerpt[:400].rsplit(" ", 1)[0] + "…"
    return excerpt + "\n\n#shorts"


# 🧹 v1.2.13: fallback lokal bila helper app.py tidak bisa diimpor di
# proses worker ini — jaga tetap selaras dengan _clean_upload_text
# di app.py (buang emoji/simbol/kontrol, hanya teks polos yang lolos).
_CLIP_CLEAN_REMOVE_RE = re.compile(
    '['
    '\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f-\u009f'
    '\u00a9\u00ae\u2122'
    '\u200b-\u200f\u202a-\u202e\u2060-\u2064\ufeff'
    '\ufe00-\ufe0f'
    '\u20d0-\u20ff'
    '\u2190-\u21ff\u2300-\u23ff\u2460-\u24ff'
    '\u2500-\u257f\u2580-\u259f\u25a0-\u25ff\u2600-\u26ff'
    '\u2700-\u27bf\u2b00-\u2bff'
    '\u3200-\u32ff\u3300-\u33ff'
    '\ue000-\uf8ff'
    '\U0001f000-\U0001faff'
    ']')
_CLIP_CLEAN_SAFE = frozenset('.,!?-:;\'"()[]&%+/@#')


def _clip_clean_text(text, max_len=None, fallback=''):
    """Versi ringkas _clean_upload_text untuk worker Clipper."""
    import unicodedata as _ud
    s = '' if text is None else str(text)
    if not s:
        return _clip_clean_text(fallback, max_len=max_len) if fallback else ''
    s = _ud.normalize('NFC', s)
    out = []
    for ch in s:
        o = ord(ch)
        if 0xFF01 <= o <= 0xFF5E:
            out.append(chr(o - 0xFEE0))
        elif ch in ('\u2018', '\u2019', '\u201a'):
            out.append("'")
        elif ch in ('\u201c', '\u201d', '\u201e'):
            out.append('"')
        elif ch in ('\u2013', '\u2014', '\u2212'):
            out.append('-')
        elif ch == '\u2026':
            out.append('...')
        elif ch in ('\u00a0', '\u2000', '\u2001', '\u2002', '\u2003',
                    '\u2004', '\u2005', '\u2006', '\u2007', '\u2008',
                    '\u2009', '\u200a', '\u202f', '\u205f', '\u3000', '\t'):
            out.append(' ')
        elif ch == '\r':
            pass
        else:
            out.append(ch)
    s = ''.join(out)
    s = _CLIP_CLEAN_REMOVE_RE.sub('', s)
    kept = []
    for ch in s:
        if ch == '\n' or ch == ' ' or ch in _CLIP_CLEAN_SAFE or ch.isalnum() \
                or _ud.category(ch).startswith('M'):
            kept.append(ch)
    s = ''.join(kept)
    lines = [' '.join(ln.split()) for ln in s.split('\n')]
    cleaned_lines = []
    for ln in lines:
        if ln:
            cleaned_lines.append(ln)
        elif cleaned_lines and cleaned_lines[-1] != '':
            cleaned_lines.append('')
    while cleaned_lines and cleaned_lines[-1] == '':
        cleaned_lines.pop()
    s = '\n'.join(cleaned_lines)
    if max_len is not None and len(s) > max_len:
        cut = s[:max_len]
        if s[max_len] not in (' ', '\n'):
            sp = max(cut.rfind(' '), cut.rfind('\n'))
            if sp > max_len // 2:
                cut = cut[:sp]
        s = cut.rstrip(' .,!?;:-').rstrip()
    if not s and fallback:
        return _clip_clean_text(fallback, max_len=max_len)
    return s

def read_db():
    with _db_lock:
        if not os.path.exists(DB_PATH): return []
        try:
            with open(DB_PATH, 'r') as f: return json.load(f)
        except: return []

def write_db(data):
    with _db_lock:
        with open(DB_PATH, 'w') as f: json.dump(data, f, indent=4)

def update_job(job_id, status=None, progress=None, stage=None, output_file=None, extra=None):
    jobs = read_db()
    for job in jobs:
        if job['id'] == job_id:
            if status is not None: job['status'] = status
            if progress is not None: job['progress'] = progress
            if stage is not None: job['stage'] = stage
            if output_file is not None: job['output_file'] = output_file
            if extra:
                job.update(extra)
            break
    write_db(jobs)

def upload_to_youtube(video_path, job_data):
    """🔥 FASE 6 (audit C6): upload klip dengan retry 1-2x untuk error
    sementara (backoff 10 → 20 detik), judul/deskripsi dari transkrip momen
    (bukan lagi selalu 'Viral Moment #N'). privacyStatus tetap 'private'.
    Upload yang sukses ikut menghitung kuota harian project (dulu tidak
    tercatat sama sekali)."""
    try:
        from googleapiclient.discovery import build
        from google.oauth2.credentials import Credentials
        from googleapiclient.http import MediaFileUpload
        from zoneinfo import ZoneInfo

        target_id = job_data.get('options', {}).get('targetChannelId')

        with open(CHANNELS_DB, 'r') as f:
            channels = json.load(f)

        channel = next((c for c in channels if c.get('yt_id') == target_id), None)
        if not channel: raise Exception("Channel Target tidak ditemukan di database!")

        creds_str = channel.get('creds_list', [channel.get('creds_json')])[0]
        creds = Credentials.from_authorized_user_info(json.loads(creds_str))
        youtube = build('youtube', 'v3', credentials=creds)

        transcript = job_data.get('transcript_text', '')
        title = build_clip_title(transcript, job_data.get('batch_index', 1))
        # 🧹 v1.2.13: jaring pengaman terakhir — bersihkan judul &
        # deskripsi tepat sebelum videos.insert (transkrip bisa
        # mengandung emoji/simbol). Pakai helper app.py bila bisa
        # diimpor, fallback lokal bila tidak.
        try:
            from app import _clean_upload_text as _clip_clean
        except Exception:
            _clip_clean = _clip_clean_text
        title = _clip_clean(title, max_len=100, fallback='Video Tanpa Judul')
        description = _clip_clean(build_clip_description(transcript),
                                  max_len=5000, fallback=title)
        body = {
            'snippet': {'title': title, 'description': description, 'categoryId': '24'},
            'status': {'privacyStatus': 'private'}
        }

        if job_data.get('publish_date'):
            sch_obj = datetime.strptime(job_data['publish_date'], "%Y-%m-%dT%H:%M")
            sch_obj += timedelta(days=(job_data['batch_index'] - 1))
            wib = ZoneInfo("Asia/Jakarta")
            import datetime as dt
            sch_utc = sch_obj.replace(tzinfo=wib).astimezone(dt.timezone.utc)
            body['status']['publishAt'] = sch_utc.strftime("%Y-%m-%dT%H:%M:%S.000Z")

        last_err = None
        for attempt in range(1, CLIP_UPLOAD_MAX_ATTEMPTS + 1):
            try:
                media = MediaFileUpload(video_path, resumable=True)
                req = youtube.videos().insert(part=','.join(body.keys()), body=body, media_body=media)

                response = None
                while response is None:
                    status, response = req.next_chunk()
                    if status:
                        update_job(job_data['id'], progress=int(status.progress()*100), stage=f"Mengunggah ke YT... {int(status.progress()*100)}%")

                video_id = response.get('id')
                # Upload clipper ikut menghitung kuota harian project.
                try:
                    from app import track_daily_upload as _track
                    _track(target_id)
                except Exception:
                    pass
                return video_id
            except Exception as e:
                last_err = e
                if attempt < CLIP_UPLOAD_MAX_ATTEMPTS and _is_transient_error(e):
                    time.sleep(10 * attempt)
                    continue
                raise
        raise last_err
    except Exception as e:
        raise Exception(f"Gagal Upload YT: {str(e)}")

def clipper_worker_loop():
    print("🚀 [Clipper Pro Worker] Background thread dimulai...")
    while True:
        try:
            jobs = read_db()
            # 🔥 FASE 6 (audit C7): job yang sedang menunggu retry otomatis
            # (retry_at di masa depan) jangan langsung diambil lagi.
            now_ts = time.time()
            job_to_run = next((j for j in jobs if j.get('status') == 'queued'
                               and (j.get('retry_at') or 0) <= now_ts), None)

            if job_to_run:
                job_id = job_to_run['id']
                opts = job_to_run.get('options', {})
                batch_idx = job_to_run.get('batch_index', 1)
                total_batch = job_to_run.get('total_batch', 1)
                
                update_job(job_id, status='processing', stage='Menunggu slot CPU/RAM kosong...')
                # Temuan #16: acquire_resource() kini melempar TimeoutError
                # (default 600 dtk) bila RAM tak kunjung lega / lock tak
                # lepas — kembalikan job ke antrean dengan retry 60 dtk
                # supaya tidak terjebak selamanya di status 'processing'.
                try:
                    acquire_resource(worker_name="Clipper Worker")
                except TimeoutError as gate_err:
                    update_job(job_id, status='queued',
                               stage=f"Slot CPU/RAM sibuk, coba lagi otomatis... ({gate_err})",
                               extra={"retry_at": time.time() + 60})
                    print(f"⚠️ [Clipper Worker] Job {job_id} menunggu resource timeout, dijadwalkan ulang: {gate_err}")
                    continue

                temp_files = []
                try:
                    # 1. DOWNLOAD
                    # 🔥 FASE 6 (audit C4): kunci cache = ID video asli dari
                    # URL (disimpan di job saat start), bukan timestamp job.
                    update_job(job_id, status='downloading', progress=20, stage='Mengunduh video sumber...')
                    source_path = download_source(url=job_to_run['url'], video_id=job_to_run.get('source_video_id') or job_id.split('_')[0], resolution="1080p")

                    # 2. DETEKSI VIRAL MOMENT (AI)
                    # 🔥 FASE 6 (audit C2): hasil deteksi di-cache per video
                    # sumber — job lain dalam batch yang sama tidak memindai
                    # ulang video penuh.
                    update_job(job_id, status='clipping', progress=40, stage='Menganalisis momen viral (AI)...')
                    moments = get_viral_moments_cached(source_path, count=total_batch, duration_sec=40)
                    my_moment = moments[batch_idx - 1] if batch_idx <= len(moments) else moments[0]
                    
                    start_time = my_moment['start']
                    duration = my_moment['duration']
                    
                    # --- PERSIAPAN AUDIO BGM DILAKUKAN LEBIH AWAL ---
                    bgm_file = opts.get('bgmFile', 'none')
                    audio_mode = opts.get('audioMode', 'bgm')
                    asset_id = opts.get('assetChannelId', '')
                    bgm_path = None
                    
                    if bgm_file != 'none' and asset_id:
                        # Temuan #19: path BGM di-contain di bawah
                        # uploads/<assetChannelId>; path absolut/traversal
                        # mengembalikan None (diperlakukan tanpa BGM).
                        bgm_path = resolve_bgm_path(asset_id, bgm_file)
                    
                    # 3. POTONG AUDIO & GENERATE LIRIK (Auto-Switch Sumber Suara)
                    srt_path = None
                    if opts.get('lyricStyle') != 'none':
                        update_job(job_id, status='clipping', progress=60, stage='Generate Lirik via AI...')
                        audio_clip = f"{source_path}_{job_id}_audio.mp3"
                        temp_files.append(audio_clip)
                        
                        # LOGIKA PINTAR: Pilih suara apa yang akan didengarkan oleh AI
                        if audio_mode == "replace" and bgm_path and os.path.exists(bgm_path):
                            # Jika Mute Mode: Potong lagu BGM sesuai durasi video dan kirim ke AI
                            subprocess.run(['/usr/bin/ffmpeg', '-y', '-stream_loop', '-1', '-i', bgm_path, '-t', str(duration), '-q:a', '0', '-map', 'a', audio_clip], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                        else:
                            # Jika BGM Mode: Potong suara asli dari video dan kirim ke AI
                            subprocess.run(['/usr/bin/ffmpeg', '-y', '-ss', str(start_time), '-t', str(duration), '-i', source_path, '-q:a', '0', '-map', 'a', audio_clip], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                        
                        # Rotasi global lintas semua provider.
                        # ai_provider lama tidak lagi membatasi penggunaan token.
                        srt_path = generate_lyrics_srt(
                            audio_clip,
                            job_to_run.get('api_keys', []),
                            provider='auto'
                        )
                        if srt_path: temp_files.append(srt_path)
                        # 🔥 FASE 6 (audit C6): simpan transkrip untuk bahan
                        # judul/deskripsi klip saat upload ke YouTube.
                        if srt_path:
                            job_to_run['transcript_text'] = extract_transcript_text(srt_path)

                    # 4. RENDER FINAL (Crop + Visualizer + Lirik + Audio Mix)
                    update_job(job_id, status='encoding', progress=80, stage='Rendering Efek & Filter FFmpeg...')
                    output_name = f"clip_{job_id}.mp4"
                    output_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'static', output_name)
                    
                    process_clip_pro(
                        source_path=source_path,
                        output_path=output_path,
                        start_time=start_time,
                        duration=duration,
                        crop_mode=opts.get('cropMode', 'center'),
                        lyric_style=opts.get('lyricStyle', 'none'),
                        srt_path=srt_path,
                        use_visualizer=opts.get('useVisualizer', False),
                        bgm_path=bgm_path,
                        audio_mode=audio_mode,
                        custom_font=opts.get('customFont', '')
                    )
                    
                    # 5. DESTINASI OUTPUT
                    dest = opts.get('outputDest', 'local')
                    target_id = opts.get('targetChannelId', '')
                    
                    if dest == 'youtube' and target_id:
                        update_job(job_id, status='encoding', progress=95, stage='Proses Upload ke YouTube...')
                        yt_id = upload_to_youtube(output_path, job_to_run)
                        final_msg = f"Selesai & Dijadwalkan! (YT ID: {yt_id})"
                    elif dest == 'drive':
                        update_job(job_id, status='encoding', progress=95, stage='Mengirim ke Google Drive...')
                        final_msg = "Selesai (Tersimpan di Drive)"
                    elif dest == 'dropbox':
                        update_job(job_id, status='encoding', progress=95, stage='Mengirim ke Dropbox...')
                        final_msg = "Selesai (Tersimpan di Dropbox)"
                    else:
                        final_msg = "Selesai (Tersimpan di Galeri/Lokal)."

                    update_job(job_id, status='done', progress=100, stage=final_msg, output_file=output_name)
                    print(f"✅ [Clipper Worker] Job {job_id} selesai.")
                    
                except Exception as e:
                    # 🔥 FASE 6 (audit C7): error SEMENTARA (download/timeout/
                    # jaringan) dicoba lagi otomatis maks 2x (backoff 10 → 20
                    # dtk). Kalau sudah habis percobaan / error permanen →
                    # status error + notifikasi Telegram ke Bos.
                    attempts = int(job_to_run.get('attempts', 0)) + 1
                    if attempts < CLIP_JOB_MAX_ATTEMPTS and _is_transient_error(e):
                        wait = 10 * attempts
                        update_job(job_id, status='queued',
                                   stage=f"Gagal sementara, coba lagi otomatis ({attempts}/{CLIP_JOB_MAX_ATTEMPTS})... 😅",
                                   extra={"attempts": attempts, "retry_at": time.time() + wait})
                        print(f"⚠️ [Clipper Worker] Job {job_id} gagal sementara, retry {attempts} dalam {wait} dtk: {e}")
                    else:
                        print(f"❌ [Clipper Worker] Error job {job_id}: {e}")
                        update_job(job_id, status='error', stage=f'Error: {str(e)}',
                                   extra={"attempts": attempts})
                        _clipper_notify("❌", f"Klip Shorts #{batch_idx} gagal 😅",
                                        f"URL: {str(job_to_run.get('url', ''))[:80]}\nPenyebab: {str(e)[:120]}\nSaya udah coba {attempts}x, Bos — cek panel ya 👀")

                finally:
                    for tf in temp_files:
                        if os.path.exists(tf):
                            try: os.remove(tf)
                            except: pass

                    # 🔥 FASE 6 (audit C4): file sumber download TIDAK lagi
                    # dihapus di akhir batch — file itu cache bersama (kunci
                    # ID video) untuk batch berikutnya dari URL yang sama.
                    # Pembersih berkala Fase 5 menghapusnya setelah > 7 hari.

                    release_resource(worker_name="Clipper Worker")
                    
        except Exception as main_e:
            print(f"⚠️ [Clipper Worker] Fatal error: {main_e}")
            
        time.sleep(2)

threading.Thread(target=clipper_worker_loop, daemon=True).start()